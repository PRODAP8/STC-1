#!/usr/bin/env python3
"""Renders the instrument multisamples used by the plugin from the MIT-licensed
MuseScore_General soundfont (needs: fluidsynth, oggenc, numpy, scipy).

    python3 tools/make_samples.py /usr/share/sounds/sf3/MuseScore_General_Lite.sf3

Output: Resources/inst_<name>.ogg  (9 or 7 notes, 4 s slots, mono, 32 kHz) and Source/InstrumentTable.h
"""
import os, struct, subprocess, sys, tempfile
import numpy as np
from scipy.io import wavfile

SF = sys.argv[1] if len(sys.argv) > 1 else "/usr/share/sounds/sf3/MuseScore_General_Lite.sf3"
RATE, SLOT, HOLD = 32000, 4.0, 3.2
HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "Resources")
os.makedirs(OUT, exist_ok=True)

CHORD_ROOTS = list(range(51, 76, 3))     # 51..75
BASS_ROOTS = list(range(33, 52, 3))      # 33..51
# name, GM program, looped (sustains), roots
INSTR = [
    ("piano",   0,  False, CHORD_ROOTS),
    ("keys",    5,  False, CHORD_ROOTS),
    ("rhodes",  4,  False, CHORD_ROOTS),
    ("synth",   90, True,  CHORD_ROOTS),
    ("pad",     89, True,  CHORD_ROOTS),
    ("organ",   16, True,  CHORD_ROOTS),
    ("strings", 48, True,  CHORD_ROOTS),
    ("guitar",  24, False, CHORD_ROOTS),
    ("bass",    33, False, BASS_ROOTS),
]

def vlq(n):
    b = [n & 0x7F]
    n >>= 7
    while n:
        b.append((n & 0x7F) | 0x80)
        n >>= 7
    return bytes(reversed(b))

def make_midi(program, roots):
    tpq = 480                      # 120 bpm -> 1 beat = 0.5 s
    ticks = lambda sec: int(sec * 2 * tpq)
    ev = [(0, bytes([0xC0, program]))]
    for i, n in enumerate(roots):
        ev.append((ticks(i * SLOT), bytes([0x90, n, 100])))
        ev.append((ticks(i * SLOT + HOLD), bytes([0x80, n, 0])))
    ev.sort(key=lambda e: e[0])
    trk = b"\x00\xff\x51\x03\x07\xa1\x20"
    last = 0
    for t, d in ev:
        trk += vlq(t - last) + d
        last = t
    trk += vlq(ticks(len(roots) * SLOT) - last) + b"\xff\x2f\x00"
    return b"MThd" + struct.pack(">IHHH", 6, 0, 1, tpq) + b"MTrk" + struct.pack(">I", len(trk)) + trk

table = []
for name, prog, looped, roots in INSTR:
    with tempfile.TemporaryDirectory() as td:
        mid, wav = os.path.join(td, "a.mid"), os.path.join(td, "a.wav")
        open(mid, "wb").write(make_midi(prog, roots))
        subprocess.run(["fluidsynth", "-ni", "-r", str(RATE), "-g", "1.0",
                        "-o", "synth.reverb.active=0", "-o", "synth.chorus.active=0",
                        "-F", wav, SF, mid], check=True, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
        sr, data = wavfile.read(wav)
        data = data.astype(np.float32) / 32768.0
        if data.ndim > 1:
            data = data.mean(axis=1)

    slot = int(SLOT * RATE)
    out = np.zeros(slot * len(roots), dtype=np.float32)
    for i in range(len(roots)):
        seg = data[i * slot:(i + 1) * slot].copy()
        if len(seg) < slot:
            seg = np.pad(seg, (0, slot - len(seg)))
        ref = seg[int(0.1 * RATE):int(1.6 * RATE)]
        rms = float(np.sqrt(np.mean(ref ** 2))) + 1e-9
        seg *= 0.12 / rms
        peak = float(np.max(np.abs(seg)))
        if peak > 0.9:
            seg *= 0.9 / peak
        fade = int(0.15 * RATE)
        seg[-fade:] *= np.linspace(1, 0, fade)
        out[i * slot:(i + 1) * slot] = seg

    with tempfile.TemporaryDirectory() as td:
        w = os.path.join(td, "o.wav")
        wavfile.write(w, RATE, (out * 32767).astype(np.int16))
        subprocess.run(["oggenc", "-q", "3", "-Q", "-o", os.path.join(OUT, f"inst_{name}.ogg"), w], check=True)
    table.append((name, looped, roots))
    print(name, "ok", os.path.getsize(os.path.join(OUT, f"inst_{name}.ogg")) // 1024, "KB")

with open(os.path.join(HERE, "..", "Source", "InstrumentTable.h"), "w") as f:
    f.write("// generated by tools/make_samples.py - do not edit\n#pragma once\n#include <array>\n\nnamespace inst\n{\n")
    f.write(f"constexpr int kRate = {RATE};\nconstexpr double kSlot = {SLOT};\nconstexpr int kCount = {len(table)};\n")
    f.write("struct Def { const char* file; const char* label; bool looped; int numRoots; int roots[12]; };\n")
    f.write("constexpr Def defs[kCount] = {\n")
    for name, looped, roots in table:
        r = ", ".join(str(x) for x in roots)
        f.write(f'    {{ "inst_{name}_ogg", "{name}", {"true" if looped else "false"}, {len(roots)}, {{ {r} }} }},\n')
    f.write("};\n}\n")
